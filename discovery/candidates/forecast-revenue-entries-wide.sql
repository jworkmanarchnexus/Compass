SELECT p.WBS1 AS project,
       LTRIM(RTRIM(ISNULL(e.LastName, ''))) + ', ' + LTRIM(RTRIM(ISNULL(e.FirstName, ''))) AS pic,
       ISNULL(t.Description, p.ProjectType) AS sector,
       p.Name AS name,
       ISNULL(L.c_oct, 0) AS lab_c_oct,
       ISNULL(L.b_oct, 0) AS lab_b_oct,
       ISNULL(L.e_oct, 0) AS lab_e_oct,
       ISNULL(L.c_nov, 0) AS lab_c_nov,
       ISNULL(L.b_nov, 0) AS lab_b_nov,
       ISNULL(L.e_nov, 0) AS lab_e_nov,
       ISNULL(L.c_dec, 0) AS lab_c_dec,
       ISNULL(L.b_dec, 0) AS lab_b_dec,
       ISNULL(L.e_dec, 0) AS lab_e_dec,
       ISNULL(C.c_oct, 0) AS con_c_oct,
       ISNULL(C.b_oct, 0) AS con_b_oct,
       ISNULL(C.e_oct, 0) AS con_e_oct,
       ISNULL(C.c_nov, 0) AS con_c_nov,
       ISNULL(C.b_nov, 0) AS con_b_nov,
       ISNULL(C.e_nov, 0) AS con_e_nov,
       ISNULL(C.c_dec, 0) AS con_c_dec,
       ISNULL(C.b_dec, 0) AS con_b_dec,
       ISNULL(C.e_dec, 0) AS con_e_dec,
       ISNULL(X.c_oct, 0) AS exp_c_oct,
       ISNULL(X.b_oct, 0) AS exp_b_oct,
       ISNULL(X.e_oct, 0) AS exp_e_oct,
       ISNULL(X.c_nov, 0) AS exp_c_nov,
       ISNULL(X.b_nov, 0) AS exp_b_nov,
       ISNULL(X.e_nov, 0) AS exp_e_nov,
       ISNULL(X.c_dec, 0) AS exp_c_dec,
       ISNULL(X.b_dec, 0) AS exp_b_dec,
       ISNULL(X.e_dec, 0) AS exp_e_dec,
       ISNULL(U.c_oct, 0) AS unit_c_oct,
       ISNULL(U.b_oct, 0) AS unit_b_oct,
       ISNULL(U.e_oct, 0) AS unit_e_oct,
       ISNULL(U.c_nov, 0) AS unit_c_nov,
       ISNULL(U.b_nov, 0) AS unit_b_nov,
       ISNULL(U.e_nov, 0) AS unit_e_nov,
       ISNULL(U.c_dec, 0) AS unit_c_dec,
       ISNULL(U.b_dec, 0) AS unit_b_dec,
       ISNULL(U.e_dec, 0) AS unit_e_dec
FROM dbo.PR p
LEFT JOIN (SELECT k.WBS1,
       SUM(CASE WHEN r.StartDate >= '20261001' AND r.StartDate < '20261101' THEN r.PeriodCost ELSE 0 END) AS c_oct,
       SUM(CASE WHEN r.StartDate >= '20261001' AND r.StartDate < '20261101' THEN r.PeriodBill ELSE 0 END) AS b_oct,
       SUM(CASE WHEN r.EndDate >= '20261001' AND r.EndDate < '20261101' THEN r.PeriodCost ELSE 0 END) AS e_oct,
       SUM(CASE WHEN r.StartDate >= '20261101' AND r.StartDate < '20261201' THEN r.PeriodCost ELSE 0 END) AS c_nov,
       SUM(CASE WHEN r.StartDate >= '20261101' AND r.StartDate < '20261201' THEN r.PeriodBill ELSE 0 END) AS b_nov,
       SUM(CASE WHEN r.EndDate >= '20261101' AND r.EndDate < '20261201' THEN r.PeriodCost ELSE 0 END) AS e_nov,
       SUM(CASE WHEN r.StartDate >= '20261201' AND r.StartDate < '20270101' THEN r.PeriodCost ELSE 0 END) AS c_dec,
       SUM(CASE WHEN r.StartDate >= '20261201' AND r.StartDate < '20270101' THEN r.PeriodBill ELSE 0 END) AS b_dec,
       SUM(CASE WHEN r.EndDate >= '20261201' AND r.EndDate < '20270101' THEN r.PeriodCost ELSE 0 END) AS e_dec
       FROM dbo.PNPlannedRevenueLabor r JOIN dbo.PNTask k ON k.PlanID = r.PlanID AND k.TaskID = r.TaskID GROUP BY k.WBS1) L ON L.WBS1 = p.WBS1
LEFT JOIN (SELECT k.WBS1,
       SUM(CASE WHEN r.StartDate >= '20261001' AND r.StartDate < '20261101' THEN r.PeriodCost ELSE 0 END) AS c_oct,
       SUM(CASE WHEN r.StartDate >= '20261001' AND r.StartDate < '20261101' THEN r.PeriodBill ELSE 0 END) AS b_oct,
       SUM(CASE WHEN r.EndDate >= '20261001' AND r.EndDate < '20261101' THEN r.PeriodCost ELSE 0 END) AS e_oct,
       SUM(CASE WHEN r.StartDate >= '20261101' AND r.StartDate < '20261201' THEN r.PeriodCost ELSE 0 END) AS c_nov,
       SUM(CASE WHEN r.StartDate >= '20261101' AND r.StartDate < '20261201' THEN r.PeriodBill ELSE 0 END) AS b_nov,
       SUM(CASE WHEN r.EndDate >= '20261101' AND r.EndDate < '20261201' THEN r.PeriodCost ELSE 0 END) AS e_nov,
       SUM(CASE WHEN r.StartDate >= '20261201' AND r.StartDate < '20270101' THEN r.PeriodCost ELSE 0 END) AS c_dec,
       SUM(CASE WHEN r.StartDate >= '20261201' AND r.StartDate < '20270101' THEN r.PeriodBill ELSE 0 END) AS b_dec,
       SUM(CASE WHEN r.EndDate >= '20261201' AND r.EndDate < '20270101' THEN r.PeriodCost ELSE 0 END) AS e_dec
       FROM dbo.PNPlannedConsultant r JOIN dbo.PNTask k ON k.PlanID = r.PlanID AND k.TaskID = r.TaskID GROUP BY k.WBS1) C ON C.WBS1 = p.WBS1
LEFT JOIN (SELECT k.WBS1,
       SUM(CASE WHEN r.StartDate >= '20261001' AND r.StartDate < '20261101' THEN r.PeriodCost ELSE 0 END) AS c_oct,
       SUM(CASE WHEN r.StartDate >= '20261001' AND r.StartDate < '20261101' THEN r.PeriodBill ELSE 0 END) AS b_oct,
       SUM(CASE WHEN r.EndDate >= '20261001' AND r.EndDate < '20261101' THEN r.PeriodCost ELSE 0 END) AS e_oct,
       SUM(CASE WHEN r.StartDate >= '20261101' AND r.StartDate < '20261201' THEN r.PeriodCost ELSE 0 END) AS c_nov,
       SUM(CASE WHEN r.StartDate >= '20261101' AND r.StartDate < '20261201' THEN r.PeriodBill ELSE 0 END) AS b_nov,
       SUM(CASE WHEN r.EndDate >= '20261101' AND r.EndDate < '20261201' THEN r.PeriodCost ELSE 0 END) AS e_nov,
       SUM(CASE WHEN r.StartDate >= '20261201' AND r.StartDate < '20270101' THEN r.PeriodCost ELSE 0 END) AS c_dec,
       SUM(CASE WHEN r.StartDate >= '20261201' AND r.StartDate < '20270101' THEN r.PeriodBill ELSE 0 END) AS b_dec,
       SUM(CASE WHEN r.EndDate >= '20261201' AND r.EndDate < '20270101' THEN r.PeriodCost ELSE 0 END) AS e_dec
       FROM dbo.PNPlannedExpenses r JOIN dbo.PNTask k ON k.PlanID = r.PlanID AND k.TaskID = r.TaskID GROUP BY k.WBS1) X ON X.WBS1 = p.WBS1
LEFT JOIN (SELECT k.WBS1,
       SUM(CASE WHEN r.StartDate >= '20261001' AND r.StartDate < '20261101' THEN r.PeriodCost ELSE 0 END) AS c_oct,
       SUM(CASE WHEN r.StartDate >= '20261001' AND r.StartDate < '20261101' THEN r.PeriodBill ELSE 0 END) AS b_oct,
       SUM(CASE WHEN r.EndDate >= '20261001' AND r.EndDate < '20261101' THEN r.PeriodCost ELSE 0 END) AS e_oct,
       SUM(CASE WHEN r.StartDate >= '20261101' AND r.StartDate < '20261201' THEN r.PeriodCost ELSE 0 END) AS c_nov,
       SUM(CASE WHEN r.StartDate >= '20261101' AND r.StartDate < '20261201' THEN r.PeriodBill ELSE 0 END) AS b_nov,
       SUM(CASE WHEN r.EndDate >= '20261101' AND r.EndDate < '20261201' THEN r.PeriodCost ELSE 0 END) AS e_nov,
       SUM(CASE WHEN r.StartDate >= '20261201' AND r.StartDate < '20270101' THEN r.PeriodCost ELSE 0 END) AS c_dec,
       SUM(CASE WHEN r.StartDate >= '20261201' AND r.StartDate < '20270101' THEN r.PeriodBill ELSE 0 END) AS b_dec,
       SUM(CASE WHEN r.EndDate >= '20261201' AND r.EndDate < '20270101' THEN r.PeriodCost ELSE 0 END) AS e_dec
       FROM dbo.PNPlannedUnit r JOIN dbo.PNTask k ON k.PlanID = r.PlanID AND k.TaskID = r.TaskID GROUP BY k.WBS1) U ON U.WBS1 = p.WBS1
LEFT JOIN dbo.EMMain e ON e.Employee = p.Principal
LEFT JOIN (SELECT Code, MIN(Description) AS Description FROM dbo.CFGProjectTypeDescriptions GROUP BY Code) t ON t.Code = p.ProjectType
WHERE p.WBS2 = '' AND p.WBS3 = '' AND p.Status = 'A' AND p.WBS1 NOT LIKE '[A-Za-z]%'
